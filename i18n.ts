export type MessageKey = keyof typeof ENGLISH_MESSAGES;
export type TranslationValues = Readonly<Record<string, string | number>>;

let currentLanguage: UiLanguage = DEFAULT_UI_LANGUAGE;

export function isUiLanguage(value: unknown): value is UiLanguage {
	return typeof value === "string" && (SUPPORTED_UI_LANGUAGES as readonly string[]).includes(value);
}

export function getUiLanguage(): UiLanguage {
	return currentLanguage;
}

export function setUiLanguage(language: UiLanguage): void {
	currentLanguage = language;
}

function interpolate(template: string, values: TranslationValues): string {
	return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (placeholder, name: string) => {
		const value = values[name];
		return value === undefined ? placeholder : String(value);
	});
}

export function t(key: MessageKey, values: TranslationValues = {}): string {
	const template = currentLanguage === "en" ? ENGLISH_MESSAGES[key] : key;
	return interpolate(template, values);
}

export function joinLocalizedList(items: readonly string[]): string {
	return items.join(currentLanguage === "en" ? ", " : "、");
}

export function getEnglishMessageEntries(): ReadonlyArray<readonly [MessageKey, string]> {
	return Object.entries(ENGLISH_MESSAGES) as Array<[MessageKey, string]>;
}
